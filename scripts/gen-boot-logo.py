#!/usr/bin/env python3
"""Generate patches/xnu/zzzzzzzzzzzz-guamp-boot-logo.patch: white Apple logo on black at boot (29/10).

The guamp kernel is built with XNU_BOOT_PROGRESS=0 (package/BootProgress.c is not linked), so the logo lives in
XNU itself: new osfmk/console/guamp_boot_logo.h, called at the end of initialize_screen() in video_console.c,
after zzz-boot-progress.patch (whose boot_progress_bind() line is the context). Painted once, at the first call
with a mapped 32-bit framebuffer; never again (backboardd's frames replace it). guamp-logo=0 disables it; an
active boot-progress page (XNU_BOOT_PROGRESS=1 builds) wins. Marker string guamp-logo-1029.

Artwork (29/10 pm): preferably the device tree property /chosen/guamp-logo, made LOCALLY from the IPSW's iBoot logo
(Codex/logo-avvio/prepara-logo.py + aggiungi-logo-adt.py; Apple file, never in this repository): 'GLG1', u16 width,
u16 height, s16 dy, u16 0, then width*height 8-bit coverage, drawn 1:1 centred (+dy). Fallback when the property is
missing or invalid: XNU's own pexpert/pexpert/AppleBoot.h + Clut.h (APSL 2.0), 128x128 CLUT indices (grey 191 =
background, 115 = logo), cropped, enlarged SCALE times (Catmull-Rom bicubic), 8-bit coverage, compiled in.
Usage: gen-boot-logo.py <xnu-source> <device-repo-root> [scale]
"""
import re, subprocess, sys, tempfile, shutil
from pathlib import Path
xnu, repo = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
scale = float(sys.argv[3]) if len(sys.argv) > 3 else 1.5   # ~129x158, the size of the IPSW logo on this panel
def values(text, start):
    body = text[text.index('{', text.index(start)) + 1:]
    return [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', body[:body.index('}')])]
pict = values((xnu / 'pexpert/pexpert/AppleBoot.h').read_text(), 'gAppleBootPict')
clut = values((xnu / 'pexpert/pexpert/Clut.h').read_text(), 'gClut')
assert len(pict) == 128 * 128 and len(clut) == 768
src = [[max(0.0, min(1.0, (191 - clut[pict[y * 128 + x] * 3]) / (191 - 115))) for x in range(128)] for y in range(128)]
ys = [y for y in range(128) if any(src[y])]; xs = [x for x in range(128) if any(src[y][x] for y in range(128))]
x0, x1, y0, y1 = xs[0] - 1, xs[-1] + 2, ys[0] - 1, ys[-1] + 2
W, H = int((x1 - x0) * scale), int((y1 - y0) * scale)
at = lambda x, y: src[y][x] if 0 <= x < 128 and 0 <= y < 128 else 0.0
def cr(t):  # Catmull-Rom weights for the 4 taps around t in [0,1)
    return [((-t + 2) * t - 1) * t / 2, ((3 * t - 5) * t * t + 2) / 2, ((-3 * t + 4) * t + 1) * t / 2, (t - 1) * t * t / 2]
rows = []
for oy in range(H):
    sy = y0 + (oy + 0.5) / scale - 0.5; iy = int(sy // 1); wy = cr(sy - iy); row = []
    for ox in range(W):
        sx = x0 + (ox + 0.5) / scale - 0.5; ix = int(sx // 1); wx = cr(sx - ix)
        v = sum(wy[j] * sum(wx[i] * at(ix - 1 + i, iy - 1 + j) for i in range(4)) for j in range(4))
        row.append(max(0, min(255, round(v * 255))))
    rows.append(row)
header = f'''/*
 * guamp (Moto G9 Play) boot logo, GENERATED by scripts/gen-boot-logo.py (device repository).
 * Preferred: /chosen/guamp-logo from the device tree (made locally from the IPSW, never in the repository).
 * Fallback artwork from pexpert/pexpert/AppleBoot.h + Clut.h (APSL 2.0): 8-bit coverage of the white logo on black.
 */
#include <pexpert/device_tree.h>
#ifndef GUAMP_BOOT_LOGO_H
#define GUAMP_BOOT_LOGO_H
#define GUAMP_LOGO_WIDTH {W}
#define GUAMP_LOGO_HEIGHT {H}
static const unsigned char guamp_logo_alpha[GUAMP_LOGO_HEIGHT * GUAMP_LOGO_WIDTH] = {{
''' + '\n'.join(''.join(f'{v},' for v in r) for r in rows) + '''
};
/* Marker looked for by prepara-boot-smp-fix.py --logo; stored below so neither compiler nor linker drops it. */
__attribute__((used)) static const char guamp_logo_marker[] = "guamp-logo-1029";
static const char *volatile guamp_logo_tag;

/* /chosen/guamp-logo: 'GLG1', u16 width, u16 height, s16 dy, u16 0, width*height coverage bytes. */
static int
guamp_logo_from_dt(const unsigned char **alpha, unsigned int *lw, unsigned int *lh, int *dy)
{
	DTEntry entry;
	void const *value;
	unsigned int size;

	if (SecureDTLookupEntry(NULL, "/chosen", &entry) != kSuccess ||
	    SecureDTGetProperty(entry, "guamp-logo", &value, &size) != kSuccess || size < 12) {
		return 0;
	}
	const unsigned char *b = (const unsigned char *)value;
	unsigned int w = b[4] | (unsigned int)b[5] << 8, h = b[6] | (unsigned int)b[7] << 8;
	if (b[0] != 'G' || b[1] != 'L' || b[2] != 'G' || b[3] != '1' || !w || !h || w > 4096 || h > 4096 ||
	    size != 12 + w * h) {
		return 0;
	}
	*alpha = b + 12; *lw = w; *lh = h; *dy = (int16_t)(b[8] | b[9] << 8);
	return 1;
}

/* 1 = device tree logo, 2 = built-in fallback, 0 = not painted (readable with a debugger or a kernel probe). */
static volatile unsigned int guamp_logo_source;

static void
guamp_boot_logo(vm_offset_t base, unsigned int w, unsigned int h, unsigned int rb, unsigned int depth)
{
	static int done;
	unsigned int on = 1;
	const unsigned char *alpha = guamp_logo_alpha;
	unsigned int lw = GUAMP_LOGO_WIDTH, lh = GUAMP_LOGO_HEIGHT;
	int dy = 0;

	if (done) {
		return;
	}
	if (boot_progress_active()) {           /* the diagnostic page owns the screen */
		done = 1;
		return;
	}
	/* Wait for XNU's own 32-bit kernel mapping of the framebuffer (same checks as the boot-progress page). */
	if (base < 0xffff000000000000ULL || depth != 32 || w < 64 || w > 4096 ||
	    h < 64 || h > 4096 || rb < w * 4 || rb > 65536) {
		return;
	}
	done = 1;
	guamp_logo_tag = guamp_logo_marker;
	PE_parse_boot_argn("guamp-logo", &on, sizeof(on));
	if (!on) {
		return;
	}
	guamp_logo_source = 2;
	if (guamp_logo_from_dt(&alpha, &lw, &lh, &dy) && lw <= w && lh <= h) {
		guamp_logo_source = 1;
	} else {
		alpha = guamp_logo_alpha; lw = GUAMP_LOGO_WIDTH; lh = GUAMP_LOGO_HEIGHT; dy = 0;
	}
	if (lw > w || lh > h) {
		guamp_logo_source = 0;
		return;
	}
	int top = (int)(h - lh) / 2 + dy;
	if (top < 0) {
		top = 0;
	} else if (top > (int)(h - lh)) {
		top = (int)(h - lh);
	}
	unsigned int x0 = (w - lw) / 2, y0 = (unsigned int)top;
	for (unsigned int y = 0; y < h; y++) {
		volatile uint32_t *row = (volatile uint32_t *)(base + (vm_offset_t)y * rb);
		const unsigned char *a = (y >= y0 && y < y0 + lh) ? &alpha[(y - y0) * lw] : NULL;
		for (unsigned int x = 0; x < w; x++) {
			unsigned int v = (a && x >= x0 && x < x0 + lw) ? a[x - x0] : 0;
			row[x] = 0xff000000u | (v * 0x010101u);
		}
	}
	__asm__ volatile ("dsb sy" ::: "memory");
}
#endif /* GUAMP_BOOT_LOGO_H */
'''
# Patch against the source with zzz-boot-progress.patch applied (its boot_progress_bind() lines are the context).
work = Path(tempfile.mkdtemp())
try:
    (work / 'osfmk/console').mkdir(parents=True)
    shutil.copy(xnu / 'osfmk/console/video_console.c', work / 'osfmk/console/')
    git = lambda *a: subprocess.run(['git', '-C', str(work), '-c', 'user.name=x', '-c', 'user.email=x@x', *a], check=True, capture_output=True)
    git('init', '-q'); git('apply', '--include=osfmk/console/video_console.c', str(repo / 'patches/xnu/zzz-boot-progress.patch'))
    git('add', '-A'); git('commit', '-qm', 'base')
    vc = work / 'osfmk/console/video_console.c'; s = vc.read_text()
    head = '\nvoid\ninitialize_screen(PE_Video * boot_vinfo, unsigned int op)\n'; assert s.count(head) == 1
    s = s.replace(head, '\n#include "guamp_boot_logo.h"   /* guamp: after every XNU header (vm_offset_t, PE_parse_boot_argn) */\n' + head)
    tail = '''	/* Console initialization/acquisition may clear the existing mapping. */
	boot_progress_bind(vinfo.v_baseaddr, vinfo.v_width, vinfo.v_height,
	    vinfo.v_rowbytes, vinfo.v_depth);
'''
    assert s.count(tail) == 1
    s = s.replace(tail, tail + '''	/* guamp: white Apple logo on black, once, as soon as the framebuffer is mapped (guamp-logo=0 disables). */
	guamp_boot_logo(vinfo.v_baseaddr, vinfo.v_width, vinfo.v_height,
	    vinfo.v_rowbytes, vinfo.v_depth);
''')
    vc.write_text(s); (work / 'osfmk/console/guamp_boot_logo.h').write_text(header)
    git('add', '-A')
    diff = subprocess.run(['git', '-C', str(work), 'diff', '--cached'], check=True, capture_output=True, text=True).stdout
    diff = re.sub(r'^index [0-9a-f.]+( \d+)?\n', '', diff, flags=re.M)
    (repo / 'patches/xnu/zzzzzzzzzzzz-guamp-boot-logo.patch').write_text(diff)
finally:
    shutil.rmtree(work)
print(f'logo {W}x{H} scale {scale}; patch written')
