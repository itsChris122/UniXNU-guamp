#!/usr/bin/env python3
"""Generate package/BootLogo.h: white Apple logo alpha map for the boot screen.

Source: XNU's own pexpert/pexpert/AppleBoot.h (128x128, 8-bit CLUT indices, APSL)
and pexpert/pexpert/Clut.h (gClut). Grey 191 = background, 115 = full logo.
The map is cropped to the logo and enlarged SCALE times (bilinear).
Usage: gen-boot-logo.py <xnu-source> <out.h> [scale]
"""
import re, sys
from pathlib import Path
xnu, out = Path(sys.argv[1]), Path(sys.argv[2])
scale = float(sys.argv[3]) if len(sys.argv) > 3 else 2.0
def values(text, start):
    body = text[text.index('{', text.index(start)) + 1:]
    return [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', body[:body.index('}')])]
pict = values((xnu / 'pexpert/pexpert/AppleBoot.h').read_text(), 'gAppleBootPict')
clut = values((xnu / 'pexpert/pexpert/Clut.h').read_text(), 'gClut')
assert len(pict) == 128 * 128 and len(clut) == 768
def alpha(i):
    g = clut[i * 3]
    return max(0.0, min(1.0, (191 - g) / (191 - 115)))
src = [[alpha(pict[y * 128 + x]) for x in range(128)] for y in range(128)]
ys = [y for y in range(128) if any(src[y][x] > 0 for x in range(128))]
xs = [x for x in range(128) if any(src[y][x] > 0 for y in range(128))]
x0, x1, y0, y1 = xs[0] - 1, xs[-1] + 2, ys[0] - 1, ys[-1] + 2
W, H = int((x1 - x0) * scale), int((y1 - y0) * scale)
def at(x, y):
    return src[y][x] if 0 <= x < 128 and 0 <= y < 128 else 0.0
rows = []
for oy in range(H):
    sy = y0 + (oy + 0.5) / scale - 0.5
    iy = int(sy // 1); fy = sy - iy
    row = []
    for ox in range(W):
        sx = x0 + (ox + 0.5) / scale - 0.5
        ix = int(sx // 1); fx = sx - ix
        v = (at(ix, iy) * (1 - fx) + at(ix + 1, iy) * fx) * (1 - fy) + (at(ix, iy + 1) * (1 - fx) + at(ix + 1, iy + 1) * fx) * fy
        row.append(round(v * 255))
    rows.append(row)
lines = ['// SPDX-License-Identifier: APSL-2.0',
         '// GENERATED by scripts/gen-boot-logo.py from XNU pexpert/pexpert/AppleBoot.h + Clut.h (APSL 2.0).',
         '// 8-bit coverage of the white Apple logo; 0 = black background.',
         '#pragma once',
         f'#define BOOT_LOGO_WIDTH {W}', f'#define BOOT_LOGO_HEIGHT {H}',
         'static const unsigned char boot_logo_alpha[BOOT_LOGO_HEIGHT * BOOT_LOGO_WIDTH] = {']
for row in rows:
    lines.append(''.join(f'{v},' for v in row))
lines.append('};')
out.write_text('\n'.join(lines) + '\n')
print(f'{W}x{H} scale {scale}')
